"""Bundle public campus names and boundaries without database schema changes.

Run with --fetch to refresh tmp/campus_map_outlines/campuses.json, or without
it to regenerate the Dart source from that capture. --insecure only bypasses
TLS validation for the fixed NTUT GeoServer endpoint.
"""

import argparse
from datetime import date
import json
from pathlib import Path
import ssl
import urllib.parse
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
CAPTURE = ROOT / "tmp/campus_map_outlines/campuses.json"
OUTPUT = ROOT / "lib/repositories/campus_map_campus_outlines.dart"
ENDPOINT = "https://geoserver.oga.ntut.edu.tw/ows"


def generate():
    features = json.loads(CAPTURE.read_text(encoding="utf-8"))["features"]
    lines = [
        "// Generated by tool/generate_campus_map_campuses.py. Do not edit coordinates by hand.\n",
        f"// Source: {ENDPOINT}, gis:gis_campus; prepared {date.today().isoformat()}.\n\n",
        "/// Original campus names and WGS84 boundaries, keyed by GeoServer campus ID.\n",
        "const campusMapCampusOutlines = <String, ({String name, String geometry})>{\n",
    ]
    for feature in sorted(features, key=lambda f: str(f["properties"]["id"])):
        properties = feature["properties"]
        geometry = feature["geometry"]
        if geometry["type"] not in ("Polygon", "MultiPolygon"):
            raise ValueError(f"Unsupported campus geometry: {geometry['type']}")
        coordinates = geometry["coordinates"]
        if geometry["type"] == "Polygon":
            coordinates = [coordinates]
        code = str(properties["id"])
        name = properties["name_ch"].replace("'", "\\'").replace("$", "\\$")
        if not code.isdigit():
            raise ValueError(f"Unexpected campus ID: {code}")
        encoded = json.dumps(coordinates, separators=(",", ":"))
        lines.append(f"  '{code}': (\n    name: '{name}',\n    geometry: '{encoded}',\n  ),\n")
    lines.append("};\n")
    OUTPUT.write_text("".join(lines), encoding="utf-8")
    print(f"Prepared {len(features)} campus boundaries: {OUTPUT}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fetch", action="store_true")
    parser.add_argument("--insecure", action="store_true")
    arguments = parser.parse_args()
    if arguments.fetch:
        query = urllib.parse.urlencode({"service": "WFS", "version": "1.1.0", "request": "GetFeature",
                                       "typeName": "gis:gis_campus", "outputFormat": "application/json", "SRSNAME": "EPSG:4326"})
        context = ssl._create_unverified_context() if arguments.insecure else ssl.create_default_context()
        with urllib.request.urlopen(f"{ENDPOINT}?{query}", context=context, timeout=45) as response:
            CAPTURE.parent.mkdir(parents=True, exist_ok=True)
            CAPTURE.write_bytes(response.read())
    generate()
